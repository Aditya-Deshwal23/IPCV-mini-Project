"""Copy the generated evaluation summary into the README and report.

Syllabus: Unit 7 - evaluation and reproducibility
"""

from __future__ import annotations

import re
from os.path import relpath
from pathlib import Path

START_MARKER = "<!-- BEGIN GENERATED EVALUATION SUMMARY -->"
END_MARKER = "<!-- END GENERATED EVALUATION SUMMARY -->"


def sync_summary(
    summary_path: Path, documents: tuple[Path, ...]
) -> list[Path]:
    """Replace generated-results blocks with the current evaluator summary.

    Args:
        summary_path: Markdown summary generated by the evaluation runner.
        documents: README/report files containing the generated-block markers.

    Returns:
        Paths of documents updated with the generated summary text.

    Raises:
        FileNotFoundError: If the source summary is not available.
        ValueError: If a target does not contain exactly one ordered marker pair.

    Syllabus: Unit 7 - evaluation and reproducibility
    """
    if not summary_path.is_file():
        raise FileNotFoundError(
            f"Generated summary not found at {summary_path}; run the evaluator first."
        )
    summary = summary_path.read_text(encoding="utf-8").strip()
    updated: list[Path] = []
    for document in documents:
        content = document.read_text(encoding="utf-8")
        if (
            content.count(START_MARKER) != 1
            or content.count(END_MARKER) != 1
            or content.index(START_MARKER) >= content.index(END_MARKER)
        ):
            raise ValueError(f"{document} must contain one ordered generated-summary marker pair.")
        start = content.index(START_MARKER) + len(START_MARKER)
        end = content.index(END_MARKER)
        image_prefix = Path(relpath(summary_path.parent, document.parent)).as_posix()
        embedded_summary = re.sub(
            r"(!\[[^\]]*\]\()(?!/)([^)]+\.png)(\))",
            rf"\g<1>{image_prefix}/\g<2>\g<3>",
            summary,
        )
        replacement = f"\n\n{embedded_summary}\n"
        document.write_text(content[:start] + replacement + content[end:], encoding="utf-8")
        updated.append(document)
    return updated


def main() -> int:
    """Synchronize README and report with the latest generated summary.

    Args:
        None.

    Returns:
        Zero after successfully updating both documents.

    Syllabus: Unit 7 - evaluation and reproducibility
    """
    root = Path(__file__).resolve().parents[1]
    updated = sync_summary(
        root / "results" / "summary.md",
        (root / "README.md", root / "docs" / "REPORT.md"),
    )
    for path in updated:
        print(f"Updated {path.relative_to(root)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
